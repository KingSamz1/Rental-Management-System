# ── Password reset codes ──────────────────────────────────────────────────────

def generate_password_reset_code(admin_account_id, target_account_id):
    """Admin generates a one-time password reset code for a user."""
    if not is_admin(admin_account_id):
        raise PermissionError("Only the admin account can generate password reset codes.")
    import random, string
    from utils.db import get_conn
    code = "".join(random.choices(string.ascii_uppercase + string.digits, k=8))
    now  = datetime.now().isoformat()
    with get_conn() as conn:
        # Expire any old unused codes for this account
        conn.execute(
            "DELETE FROM password_reset_codes WHERE target_account_id = ? AND used_at IS NULL",
            (target_account_id,),
        )
        conn.execute(
            "INSERT INTO password_reset_codes (code, target_account_id, created_by, created_at) "
            "VALUES (?, ?, ?, ?)",
            (code, target_account_id, admin_account_id, now),
        )
    return code


def redeem_password_reset_code(username: str, code: str) -> int:
    """
    Validate a reset code for the given username.
    Returns account_id on success, raises ValueError on failure.
    Marks the code as used.
    """
    from utils.db import get_conn, get_account_by_username
    acc = get_account_by_username(username.strip())
    if not acc:
        raise ValueError("No account found with that username.")
    now = datetime.now().isoformat()
    with get_conn() as conn:
        row = conn.execute(
            "SELECT * FROM password_reset_codes "
            "WHERE code = ? AND target_account_id = ? AND used_at IS NULL",
            (code.strip().upper(), acc["id"]),
        ).fetchone()
        if not row:
            raise ValueError("Invalid or already-used reset code. Contact support for a new one.")
        conn.execute(
            "UPDATE password_reset_codes SET used_at = ? WHERE id = ?",
            (now, row["id"]),
        )
    return acc["id"]
