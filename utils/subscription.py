"""
LandlordPro subscription logic — one subscription per account.
Calendar-month trial, then monthly recurring fee.
Renewal is done via one-time codes generated by the admin account.
"""
import calendar
import secrets
import string
from datetime import date, datetime, timedelta
from utils.db import get_conn

MONTHLY_FEE = 30_000
GRACE_DAYS = 2
ADMIN_USERNAME = "samzinov"


def _today():
    return date.today()


def _date_str(d):
    return d.isoformat()


def _parse_date(value):
    if not value:
        return None
    return datetime.strptime(value, "%Y-%m-%d").date()


def _add_month(d, months=1):
    month_index = d.month - 1 + months
    year = d.year + month_index // 12
    month = month_index % 12 + 1
    last_day = calendar.monthrange(year, month)[1]
    return date(year, month, min(d.day, last_day))


# ── subscription CRUD ─────────────────────────────────────────────────────────

def create_subscription(account_id, landlord_name):
    """Called once per account, right after create_account() on signup."""
    start = _today()
    trial_end = _add_month(start) - timedelta(days=1)
    now = datetime.now().isoformat()
    with get_conn() as conn:
        cur = conn.execute(
            """INSERT INTO subscription
               (account_id, landlord_name, trial_start, trial_end, monthly_fee, status, created_at, updated_at)
               VALUES (?, ?, ?, ?, ?, 'TRIAL', ?, ?)""",
            (account_id, landlord_name, _date_str(start), _date_str(trial_end), MONTHLY_FEE, now, now),
        )
        return cur.lastrowid


def get_subscription(account_id):
    with get_conn() as conn:
        row = conn.execute(
            "SELECT * FROM subscription WHERE account_id = ? ORDER BY id DESC LIMIT 1",
            (account_id,),
        ).fetchone()
        return dict(row) if row else None


def _due_date(sub):
    if sub["status"] == "TRIAL":
        return _parse_date(sub["trial_end"]) + timedelta(days=1)
    if sub["status"] == "ACTIVE":
        return _parse_date(sub["next_payment_date"])
    return None


def update_subscription_status(account_id):
    sub = get_subscription(account_id)
    if not sub:
        return None

    today = _today()
    status = sub["status"]
    past_due = False
    grace_days_left = 0

    if status in ("TRIAL", "ACTIVE"):
        due = _due_date(sub)
        lockout_day = due + timedelta(days=GRACE_DAYS)
        if today >= lockout_day:
            status = "EXPIRED"
        elif today >= due:
            past_due = True
            grace_days_left = (lockout_day - today).days

    if status != sub["status"]:
        with get_conn() as conn:
            conn.execute(
                "UPDATE subscription SET status = ?, updated_at = ? WHERE id = ?",
                (status, datetime.now().isoformat(), sub["id"]),
            )
        sub["status"] = status

    sub["past_due"] = past_due
    sub["grace_days_left"] = grace_days_left
    return sub


def days_remaining(account_id):
    sub = update_subscription_status(account_id)
    if not sub:
        return 0
    today = _today()
    if sub["status"] == "TRIAL":
        end_date = _parse_date(sub["trial_end"])
    elif sub["status"] == "ACTIVE":
        end_date = _parse_date(sub["next_payment_date"]) - timedelta(days=1)
    else:
        return 0
    return max(0, (end_date - today).days + 1)


def system_active(account_id):
    # Admin account always has full access regardless of subscription state
    if is_admin(account_id):
        return True
    sub = update_subscription_status(account_id)
    if not sub:
        return False
    return sub["status"] in ("TRIAL", "ACTIVE")


def subscription_payment_history(account_id):
    with get_conn() as conn:
        sub = conn.execute(
            "SELECT id FROM subscription WHERE account_id = ? ORDER BY id DESC LIMIT 1",
            (account_id,),
        ).fetchone()
        if not sub:
            return []
        rows = conn.execute(
            "SELECT * FROM subscription_payments WHERE subscription_id = ? ORDER BY payment_date DESC",
            (sub["id"],),
        ).fetchall()
        return [dict(r) for r in rows]


# ── one-time renewal codes ─────────────────────────────────────────────────────

def _make_code(length=10):
    """Generate a random uppercase alphanumeric code."""
    alphabet = string.ascii_uppercase + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


def is_admin(account_id):
    """Return True if this account is the admin (samzinov)."""
    with get_conn() as conn:
        row = conn.execute(
            "SELECT username FROM accounts WHERE id = ?", (account_id,)
        ).fetchone()
        return row and row["username"].lower() == ADMIN_USERNAME.lower()


def generate_renewal_code(admin_account_id, months=1):
    """Admin only: generate a fresh one-time renewal code."""
    if not is_admin(admin_account_id):
        raise PermissionError("Only the admin account can generate renewal codes.")
    # Collision-safe: retry on duplicate
    for _ in range(10):
        code = _make_code()
        try:
            with get_conn() as conn:
                conn.execute(
                    "INSERT INTO renewal_codes (code, months, created_by) VALUES (?, ?, ?)",
                    (code, months, admin_account_id),
                )
            return code
        except Exception:
            continue
    raise RuntimeError("Could not generate a unique code. Try again.")


def list_renewal_codes(admin_account_id):
    """Admin only: list all codes (unused and used)."""
    if not is_admin(admin_account_id):
        raise PermissionError("Only the admin account can view renewal codes.")
    with get_conn() as conn:
        rows = conn.execute(
            """SELECT rc.*, a.username AS used_by_username
               FROM renewal_codes rc
               LEFT JOIN accounts a ON a.id = rc.used_by
               ORDER BY rc.created_at DESC"""
        ).fetchall()
        return [dict(r) for r in rows]


def redeem_renewal_code(account_id, code):
    """
    Client: redeem a one-time code to extend their subscription.
    Admin can also redeem codes for their own account.
    Raises ValueError with a human-readable message on failure.
    """
    code = code.strip().upper()
    if not code:
        raise ValueError("Please enter a renewal code.")

    with get_conn() as conn:
        row = conn.execute(
            "SELECT * FROM renewal_codes WHERE code = ?", (code,)
        ).fetchone()

        if not row:
            raise ValueError("Invalid code — check with your administrator.")
        if row["used_by"] is not None:
            raise ValueError("This code has already been used.")

        sub = get_subscription(account_id)
        if not sub:
            raise ValueError("No subscription found for your account.")

        months = row["months"]
        today = _today()

        # Work out the new period
        if sub["status"] == "TRIAL":
            period_start = _parse_date(sub["trial_end"]) + timedelta(days=1)
        elif sub["status"] == "ACTIVE":
            period_start = _parse_date(sub["next_payment_date"])
        else:
            period_start = today  # expired — restart from today

        period_end = _add_month(period_start, months) - timedelta(days=1)
        next_payment = _add_month(period_start, months)
        now = datetime.now().isoformat()

        # Mark code used
        conn.execute(
            "UPDATE renewal_codes SET used_by=?, used_at=? WHERE id=?",
            (account_id, now, row["id"]),
        )

        # Record payment entry (reference = the code itself)
        conn.execute(
            """INSERT INTO subscription_payments
               (subscription_id, amount, payment_date, payment_method, transaction_reference,
                period_start, period_end, note, created_at)
               VALUES (?, ?, ?, 'Code', ?, ?, ?, ?, ?)""",
            (
                sub["id"], MONTHLY_FEE * months, _date_str(today), code,
                _date_str(period_start), _date_str(period_end),
                f"Renewed via code — {months} month(s)", now,
            ),
        )

        # Activate subscription
        conn.execute(
            """UPDATE subscription
               SET status='ACTIVE', subscription_start=?, next_payment_date=?, updated_at=?
               WHERE id=?""",
            (_date_str(period_start), _date_str(next_payment), now, sub["id"]),
        )

    return get_subscription(account_id)


# ── dev / testing helpers ─────────────────────────────────────────────────────

def fast_forward(account_id, days):
    sub = get_subscription(account_id)
    if not sub:
        raise ValueError("No subscription found.")
    with get_conn() as conn:
        if sub["status"] == "TRIAL":
            new_end = _parse_date(sub["trial_end"]) - timedelta(days=days)
            conn.execute("UPDATE subscription SET trial_end=?, updated_at=? WHERE id=?",
                         (_date_str(new_end), datetime.now().isoformat(), sub["id"]))
        else:
            new_next = _parse_date(sub["next_payment_date"]) - timedelta(days=days)
            conn.execute("UPDATE subscription SET next_payment_date=?, updated_at=? WHERE id=?",
                         (_date_str(new_next), datetime.now().isoformat(), sub["id"]))
    return update_subscription_status(account_id)


def force_expire(account_id):
    sub = get_subscription(account_id)
    if not sub:
        raise ValueError("No subscription found.")
    with get_conn() as conn:
        conn.execute("UPDATE subscription SET status='EXPIRED', updated_at=? WHERE id=?",
                     (datetime.now().isoformat(), sub["id"]))
    return get_subscription(account_id)


