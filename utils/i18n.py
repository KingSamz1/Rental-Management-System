def get_language() -> str:
    """Get language from query params (persists across pages) with session state fallback."""
    # Query params survive page navigation; session state is faster within a page
    lang = st.session_state.get("app_lang")
    if not lang:
        lang = st.query_params.get("lang", "en")
        st.session_state["app_lang"] = lang
    return lang


def set_language(lang_code: str):
    st.session_state["app_lang"] = lang_code
    st.query_params["lang"] = lang_code


def language_selector(location="sidebar"):
    lang_code    = get_language()
    current_name = next((n for n, c in LANGUAGES.items() if c == lang_code), "English")
    options      = list(LANGUAGES.keys())

    if location == "sidebar":
        chosen = st.sidebar.selectbox(
            "🌐 Language", options,
            index=options.index(current_name),
            key="_lang_selector_sb",
        )
    else:
        chosen = st.selectbox(
            "🌐 Language", options,
            index=options.index(current_name),
            key="_lang_selector_inline",
        )

    new_code = LANGUAGES[chosen]
    if new_code != lang_code:
        set_language(new_code)
        st.rerun()


def t(text: str) -> str:
    """Return translated string, or original if no translation exists."""
    lang = get_language()
    if lang == "en" or not text:
        return text
    return TRANSLATIONS.get(lang, {}).get(text, text)


